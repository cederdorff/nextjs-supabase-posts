-- ============================================
-- POST APP: USERS + POSTS
-- Run the whole file in the SQL Editor in Supabase.
-- It deletes and creates the tables again, so you can run it again to start over.
-- ============================================

DROP TABLE IF EXISTS posts;
DROP TABLE IF EXISTS users;

-- ============================================
-- USERS
-- Not connected to auth.users yet – that's the first task.
-- ============================================

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    name TEXT NOT NULL,
    mail TEXT NOT NULL,
    title TEXT,
    image TEXT
);

-- ============================================
-- POSTS
-- posts.user_id -> users.id, like posts.userId -> users.id in Post App
-- ============================================

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    caption TEXT NOT NULL,
    image TEXT NOT NULL,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

-- ============================================
-- ACCESS
-- Row Level Security is off: anyone with the publishable key
-- can read, create, change and delete everything. We fix that later.
-- ============================================

ALTER TABLE users DISABLE ROW LEVEL SECURITY;
ALTER TABLE posts DISABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON users, posts TO anon, authenticated;

